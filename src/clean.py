"""Cleaning + an auto-written data-quality report (rubric: Data Understanding).
Every filter records how many rows it removed, so the decision log can quote it."""
import re
import numpy as np
import pandas as pd
from . import config

PRIVACY_DROP = ["listing_url", "host_url", "host_name", "host_about", "host_thumbnail_url",
                "host_picture_url", "picture_url", "license"]  # licence text replaced by a category


def parse_price(s: pd.Series) -> pd.Series:
    """'$1,234.00' -> 1234.0. Prices are stored as text everywhere."""
    return pd.to_numeric(s.astype(str).str.replace(r"[$,\s]", "", regex=True), errors="coerce")


def licence_status(raw: pd.Series) -> pd.Series:
    """Categorise the licence field WITHOUT keeping the number (privacy rule).
    Categories are an estimate from free text; see docs/data_quality.md."""
    t = raw.fillna("").astype(str).str.strip().str.lower()
    out = pd.Series("missing", index=raw.index)
    out[t.str.contains("exempt")] = "exempt_claimed"
    out[t.str.contains(r"\d{2}-\d{6}|\d{6,}", regex=True)] = "has_number"
    out[t.str.contains("pending")] = "pending"
    out[(t != "") & (out == "missing")] = "other_text"
    return out


def clean_listings(df: pd.DataFrame) -> tuple[pd.DataFrame, list[dict]]:
    log = []
    def step(name, mask, why):
        log.append({"step": name, "rows_before": int(len(df_)), "removed": int((~mask).sum()), "why": why})
        return df_[mask].copy()

    df_ = df.copy()
    df_["price_num"] = parse_price(df_["price"]) if "price" in df_ else np.nan
    if "license" in df_:
        df_["licence_status"] = licence_status(df_["license"])
    df_ = df_.drop(columns=[c for c in PRIVACY_DROP if c in df_.columns])

    snap = pd.Timestamp(config.SNAPSHOT_DATE)
    df_["days_since_last_review"] = (snap - df_["last_review"]).dt.days

    df_ = step("has_price", df_["price_num"].notna(), "price missing: listing not bookable at scrape")
    df_ = step("price_in_range", df_["price_num"].between(config.MIN_NIGHTLY_PRICE, config.MAX_NIGHTLY_PRICE),
               f"outside ${config.MIN_NIGHTLY_PRICE}-${config.MAX_NIGHTLY_PRICE}/night")
    df_ = step("short_term_only", df_["minimum_nights"] <= config.MAX_MINIMUM_NIGHTS,
               "minimum stay >=30 nights is a monthly rental, outside STR scope")
    df_["is_active"] = df_["days_since_last_review"] <= config.ACTIVE_REVIEW_WINDOW_DAYS
    return df_, log


def property_bucket(df: pd.DataFrame) -> pd.Series:
    """Collapse Airbnb's ~40 property_type values into the types DDD would buy."""
    pt = df["property_type"].fillna("").str.lower()
    out = pd.Series("other", index=df.index)
    out[pt.str.contains("condo|apartment|loft|serviced")] = "condo"
    out[pt.str.contains("townhouse")] = "townhouse"
    out[pt.str.contains(r"\bhome\b|house|villa|bungalow|cottage")] = "house"
    out[pt.str.contains("guest suite|guesthouse|laneway")] = "suite"
    return out


def quality_report(raw: pd.DataFrame, log: list[dict]) -> str:
    miss = raw.isna().mean().sort_values(ascending=False).head(15)
    lines = ["# Data quality report (auto-generated by src/clean.py)\n",
             f"Snapshot: {config.SNAPSHOT_DATE}. Raw listings: {len(raw):,}. Columns: {raw.shape[1]}.\n",
             "## Filters applied\n", "| step | rows before | removed | why |", "|---|---|---|---|"]
    lines += [f"| {r['step']} | {r['rows_before']:,} | {r['removed']:,} | {r['why']} |" for r in log]
    lines += ["\n## Most-missing columns\n", "| column | % missing |", "|---|---|"]
    lines += [f"| {c} | {v:.1%} |" for c, v in miss.items()]
    lines += ["\n## Known limitations (from the brief)\n",
              "- Single-day scrape; not an official or complete list of STRs.",
              "- Unavailable calendar nights may be booked OR host-blocked.",
              "- Reviews are a proxy for stays, not a count.",
              "- Inside Airbnb occupancy/revenue fields are estimates.",
              "- Licence categories are parsed from free text; compliance rates are estimates.",
              "- City of Vancouver only; no Burnaby, Richmond, Surrey or Kelowna."]
    return "\n".join(lines) + "\n"


def run():
    from .load import load_listings
    config.PROCESSED.mkdir(parents=True, exist_ok=True)
    raw = load_listings()
    clean, log = clean_listings(raw)
    clean["bucket"] = property_bucket(clean)
    clean.to_parquet(config.PROCESSED / "listings_clean.parquet", index=False)
    (config.DOCS / "data_quality.md").write_text(quality_report(raw, log))
    print(f"clean: {len(raw):,} -> {len(clean):,} listings")
    return clean


if __name__ == "__main__":
    run()
